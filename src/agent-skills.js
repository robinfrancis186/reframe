export function detectSkills(source = '', filename = '') {
  const signals = {
    playwright: /from\s*['"](?:@playwright\/test|playwright)['"]|page\.getByRole\(/,
    gradio: /\bimport gradio\b|\bgr\.(?:Blocks|Interface|ChatInterface)\(/,
    nextjs: /from\s*['"]next(?:\/|['"])|\bgetServerSideProps\b|['"]use server['"]|next\.config/,
    'react-native': /from\s*['"]react-native['"]/,
    react: /from\s*['"]react['"]|\buseState\(|\bReact\./,
    vue: /<template[\s>]|from\s*['"]vue['"]|defineComponent\(/,
    svelte: /\$state\(|\$derived\(|\bon:click=|\.svelte$/,
    angular: /@Component\(|@Injectable\(|@angular\//,
    fastapi: /\bFastAPI\(|from fastapi import/,
    django: /from django\.|django\.db/,
    spring: /@SpringBootApplication|@RestController|org\.springframework/,
    compose: /androidx\.compose\.|@Composable\b/,
    swiftui: /import SwiftUI|:\s*(?:some\s+)?View\b/,
    flutter: /package:flutter\/|\b(?:StatelessWidget|StatefulWidget)\b/,
    dotnet: /using Microsoft\.AspNetCore|\bIActionResult\b|@page\s*"/,
    laravel: /Illuminate\\|Route::|extends\s+(?:Controller|Model)\b/,
    rails: /ApplicationController|ActiveRecord::|Rails\.application/,
    go: /\bfunc\s+\w+\(|\.go$/,
    rust: /\bfn\s+main\(|\buse\s+(?:std|axum|actix_web)::/,
    java: /\bpublic\s+(?:class|interface|static)|\.java$/,
    kotlin: /\b(?:val|var)\s+\w+\s*[:=]|\.kt$/,
    python: /\bdef\s+\w+\(|\.py$/,
    typescript: /\binterface\s+\w+|:\s*(?:string|boolean|number)\b|\.tsx?$/,
    javascript: /\b(?:const|let|function)\s+\w+|\.jsx?$/,
    html: /<(?:html|section|form|button|div)[\s>]|\.(?:html|css)$/,
  };
  return skills.filter((skill) => signals[skill.id]?.test(source + '\n' + filename));
}

