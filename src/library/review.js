export const reviewDate = '2026-10-22';
export function componentReview(entry) {
  const profile = profiles[entry.component];
  if (!profile) throw new Error('Missing component review: ' + entry.component);
  const [designBefore, codeBefore, design, code, note] = profile;
  const simplified = [
    'LibraryGallery',
    'LibraryPicker',
    'LibrarySelect',
    'LibraryOverlay',
    'LibraryRefresh',
    'LibraryMotion',
    'LibraryChart',
    'LibraryActions',
    'LibraryNavigation',
    'LibraryFiles',
  ].includes(entry.component);
  const service = entry.requirements.length > 0;
  return {
    design,
    code,
    before: Number(((designBefore + codeBefore) / 2).toFixed(1)),
    score: Number(((design + code) / 2).toFixed(1)),
    designBefore,
    codeBefore,
    note,
    level: service ? 'Service demo' : simplified ? 'Adaptation starter' : 'Interactive starter',
    scope:
      'Expert review of the shared web implementation. Native source is available; device verification is pending.',
  };
}
