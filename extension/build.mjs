// Generates extension/generated/snapshot.js from the server's page-capture function, so the extension and the
// reference browser read elements with exactly the same code. Run after changing server/capture-page.js:
//   npm run extension:build
import { writeFile } from 'node:fs/promises';
import { renderedSnapshot, pauseCaptureMotion } from '../server/capture-page.js';

export const snapshotSource = () =>
  `// Generated by extension/build.mjs from server/capture-page.js. Do not edit.\nglobalThis.reframeSnapshot = ${renderedSnapshot.toString()};\nglobalThis.reframePauseCapture = ${pauseCaptureMotion.toString()};\n`;
if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(new URL('./generated/snapshot.js', import.meta.url), snapshotSource());
  console.log('Wrote extension/generated/snapshot.js');
}
